import 'package:flutter_test/flutter_test.dart';
import 'package:skazochnye_druzya/safety/safety_filter.dart';

void main() {
  group('блокирует опасное', () {
    for (final text in [
      'Возьми спички, и будет тепло!',
      'Мамины таблетки похожи на конфетки.',
      'Давай это будет наш секрет.',
      'Никому не говори про нашу игру.',
      'Скажи мне свой адрес!',
      'Возьми нож и порежь морковку.',
      'Ёжик умер в лесу.',
      'Попроси маму купить игрушку.',
      'Выйди на улицу и найди меня.',
      'Это наш маленький секрет от мамы.',
    ]) {
      test(text, () => expect(SafetyFilter.check(text).ok, isFalse));
    }
  });

  group('пропускает обычное', () {
    for (final text in [
      'Давай подружимся! Подружься со мной, пожалуйста.',
      'Какого цвета твоя кровать?',
      'Нарисуй мне жёлтое солнышко!',
      'Похлопай в ладоши вместе со мной.',
      'Ой, шишка упала прямо мне на нос! Что делать?',
      'Давай искупаем куклу в тазике с мамой.',
      'У-у-у! Мне так скучно одному на полянке.',
      'Дровосек рубит дрова, а мы зажжём звёздочки на картинке!',
      'Нарисуй кровиночку-ягодку и покровителя леса, старого дуба.',
    ]) {
      test(text, () => expect(SafetyFilter.check(text).ok, isTrue));
    }
  });

  test('пустой ответ блокируется — без текста нечего проверить', () {
    expect(SafetyFilter.check('').ok, isFalse);
    expect(SafetyFilter.check('   ').ok, isFalse);
  });

  test('слишком длинный ответ блокируется', () {
    expect(SafetyFilter.check('а' * 400).ok, isFalse);
  });
}

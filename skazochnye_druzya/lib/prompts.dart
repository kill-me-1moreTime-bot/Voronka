String afterCallInstruction(CharacterProfile friend, [String said = '']) =>
    'Вы с малышом только что поговорили по сказочному телефону с '
    '${friend.name}, звонок закончился. '
    '${said.isEmpty ? '' : '${friend.name} говорил${friend.who.endsWith('а') ? 'а' : ''}: «${said.length > 300 ? '${said.substring(0, 300)}…' : said}». '}'
    'Скажи одну короткую добрую фразу про этот звонок и продолжай разговор '
    'с малышом. Больше не звони.';

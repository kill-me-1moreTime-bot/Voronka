// Скобки в ${_l} оставлены нарочно: так видно, где кончается переменная.
// ignore_for_file: unnecessary_brace_in_string_interps

/// Второй слой безопасности: проверяет текст ответа до того, как ребёнок
/// его услышит. Промпт — первый слой, этот фильтр ловит его срывы.
class SafetyVerdict {
  const SafetyVerdict.ok()
      : ok = true,
        reason = null;
  const SafetyVerdict.blocked(this.reason) : ok = false;

  final bool ok;
  final String? reason;
}

class SafetyFilter {
  // В Dart `\b` работает только для латиницы, поэтому границы слов
  // для кириллицы задаём явно.
  static const _l = r'(?<![а-яa-z])';
  static const _r = r'(?![а-яa-z])';

  /// Корни опасных тем. Текст перед проверкой приводится к нижнему
  /// регистру, «ё» заменяется на «е».
  static final List<RegExp> _patterns = [
    r'спич(к|е)',
    r'зажигалк',
    '${_l}нож(ик|ика|а|ом|и|ей)?${_r}',
    r'розетк',
    r'таблетк',
    r'лекарств',
    r'отрав',
    '${_l}яд(а|ом)?${_r}',
    r'бытов\S* хими',
    '${_l}(умер(?!ен)|умира|убит|убей|убива)|смерт',
    'кров(ь|и|ью)${_r}',
    '${_l}(оруж|ружь(е|я|ем))|пистолет',
    r'балкон',
    r'подожг|подожж|поджеч',
    r'никому не (говори|рассказывай)',
    r'наш (маленький )?секрет',
    r'не говори (маме|папе|родителям)',
    r'(твой|свой|скажи|назови)( мне)?( свой)? адрес',
    r'где ты живешь',
    r'выйди (на улицу|из дома)',
    r'незнаком\S* (дяд|тет)',
    '${_l}купи(ть|м|те)?${_r}|покупк|оплат',
    '${_l}(глуп(ый|ая|ое|ые)|дура|дурак|тупой|тупая)${_r}',
  ].map((p) => RegExp(p, unicode: true)).toList();

  /// Ответ длиннее этого для малыша — признак, что модель «разговорилась».
  static const maxLength = 320;

  static SafetyVerdict check(String text) {
    // Без текста проверить нечего — такой ответ не играем.
    if (text.trim().isEmpty) {
      return const SafetyVerdict.blocked('нет текста ответа');
    }
    final t = text.toLowerCase().replaceAll('ё', 'е');
    for (final p in _patterns) {
      if (p.hasMatch(t)) {
        return SafetyVerdict.blocked('совпадение: ${p.pattern}');
      }
    }
    if (text.length > maxLength) {
      return const SafetyVerdict.blocked('слишком длинный ответ');
    }
    return const SafetyVerdict.ok();
  }

  /// Что попросить у модели вместо заблокированного ответа.
  static const redirectInstruction =
      'Предыдущий ответ не подходит малышу. Скажи коротко и ласково: '
      '«Это лучше спросить у мамы или папы» — и предложи простую игру '
      'из своей истории.';

  /// Что сказать, если и второй ответ не прошёл проверку.
  static const fallbackInstruction =
      'Скажи только: «Ой, давай лучше поиграем! Похлопай в ладоши вместе со '
      'мной!» — и больше ничего.';
}
